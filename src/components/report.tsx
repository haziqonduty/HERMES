import Link from "next/link";
import { ArrowLeft, Download } from "lucide-react";
import type { StatusMeta } from "@/lib/status";
import { LogoMark } from "./logo";
import { PrintButton } from "./print-button";
import { buttonClass } from "./ui";

/** App status colours are tuned for navy; on paper each maps to a darker ink. */
const INK: Record<string, string> = {
  "var(--danger)": "var(--bad-ink)",
  "var(--warning)": "var(--warn-ink)",
  "var(--success)": "var(--ok-ink)",
  "var(--accent)": "var(--info-ink)",
  "var(--gold)": "var(--gold-ink)",
  "var(--muted)": "var(--ink-muted)",
};
export const ink = (color?: string) => (color ? (INK[color] ?? color) : undefined);

export function ReportToolbar({
  back = "/reports",
  backLabel = "Reports",
  csv,
}: {
  back?: string;
  backLabel?: string;
  csv?: { href: string; label: string }[];
}) {
  return (
    <div className="mx-auto mb-6 flex max-w-[210mm] flex-wrap items-center justify-between gap-3 print:hidden">
      <Link href={back} className="inline-flex items-center gap-1.5 text-sm text-muted hover:text-foreground">
        <ArrowLeft size={14} /> {backLabel}
      </Link>
      <div className="flex flex-wrap gap-2">
        {csv?.map((c) => (
          <a key={c.href} href={c.href} className={buttonClass()}>
            <Download size={15} /> {c.label}
          </a>
        ))}
        <PrintButton />
      </div>
    </div>
  );
}

/** A4-proportioned white document. Prints as-is. */
export function ReportSheet({
  kind,
  title,
  subtitle,
  generatedAt,
  generatedBy,
  children,
}: {
  kind: string;
  title: string;
  subtitle?: string;
  generatedAt: string;
  generatedBy: string;
  children: React.ReactNode;
}) {
  return (
    <article className="mx-auto max-w-[210mm] rounded-sm bg-paper px-10 py-10 text-[13px] leading-relaxed text-ink shadow-[0_30px_80px_-30px_rgba(0,0,0,0.8)] print:max-w-none print:p-0 print:shadow-none">
      <header className="flex items-start justify-between gap-6 border-b-2 border-gold-ink pb-5">
        <div>
          <p className="font-mono text-[10px] tracking-[0.25em] text-gold-ink">HERMES · {kind.toUpperCase()}</p>
          <h1 className="mt-2 text-2xl font-semibold tracking-tight">{title}</h1>
          {subtitle && <p className="mt-1 text-ink-muted">{subtitle}</p>}
        </div>
        <LogoMark className="h-12 w-auto shrink-0" />
      </header>
      <div className="mt-6 space-y-8">{children}</div>
      <footer className="mt-10 border-t border-rule pt-3 font-mono text-[10px] tracking-wide text-ink-muted">
        Generated by HERMES on {generatedAt} for {generatedBy}. Reflects data recorded at the time of generation.
      </footer>
    </article>
  );
}

export function RSection({ title, note, children }: { title: string; note?: React.ReactNode; children: React.ReactNode }) {
  return (
    <section className="break-inside-avoid-page">
      <div className="flex items-baseline justify-between gap-4 border-b border-rule pb-1.5">
        <h2 className="font-mono text-[11px] font-semibold tracking-[0.2em] text-gold-ink">{title.toUpperCase()}</h2>
        {note && <p className="text-[11px] text-ink-muted">{note}</p>}
      </div>
      <div className="mt-3">{children}</div>
    </section>
  );
}

export function RStats({ items }: { items: { label: string; value: React.ReactNode; color?: string }[] }) {
  return (
    <dl className="grid grid-cols-2 gap-x-6 gap-y-3 sm:grid-cols-4">
      {items.map((s) => (
        <div key={s.label}>
          <dt className="text-[11px] text-ink-muted">{s.label}</dt>
          <dd className="font-mono text-lg font-medium tabular-nums" style={{ color: ink(s.color) }}>{s.value}</dd>
        </div>
      ))}
    </dl>
  );
}

export function RTable({ head, rows, empty }: { head: string[]; rows: React.ReactNode[][]; empty: string }) {
  if (!rows.length) return <p className="text-ink-muted">{empty}</p>;
  return (
    <table className="w-full border-collapse text-left text-[12px]">
      <thead>
        <tr className="border-b border-ink/30">
          {head.map((h) => (
            <th key={h} className="whitespace-nowrap py-1.5 pr-3 font-mono text-[10px] font-medium tracking-wider text-ink-muted uppercase">{h}</th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.map((r, i) => (
          <tr key={i} className="break-inside-avoid border-b border-rule align-top">
            {r.map((c, j) => (
              <td key={j} className="py-1.5 pr-3">{c}</td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  );
}

/** Status as coloured dot + label (never colour alone). */
export function RStatus({ map, value }: { map: Record<string, StatusMeta>; value: string }) {
  const m = map[value] ?? { label: value, color: "var(--muted)" };
  return (
    <span className="inline-flex items-center gap-1.5 whitespace-nowrap" style={{ color: ink(m.color) }}>
      <span className="h-1.5 w-1.5 rounded-full" style={{ background: ink(m.color) }} />
      {m.label}
    </span>
  );
}

export const mono = "font-mono whitespace-nowrap";

/** Report timestamp in Malaysia time (the operating base), independent of the server's zone. */
export const reportStamp = (d: Date) =>
  d.toLocaleString("en-GB", { timeZone: "Asia/Kuala_Lumpur", day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" }) + " MYT";
